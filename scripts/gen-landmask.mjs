// Generates client/src/control/engine/landmask.ts: a 720 × 360 (half-degree)
// equirectangular land mask from Natural Earth's 1:50m land polygons, run-length
// encoded. The Control Center globe places its particles with it.
//
// The geometry packages aren't project dependencies; install them just for this:
//   npm i --no-save world-atlas@2 d3-geo topojson-client && node scripts/gen-landmask.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoEquirectangular, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const W = 720;
const H = 360;

const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-50m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);

// d3 cuts rings at the antimeridian while projecting, so the planar rings it
// draws can be filled with a plain even-odd scanline.
const projection = geoEquirectangular().scale(W / (2 * Math.PI)).translate([W / 2, H / 2]).precision(0.1);
const rings = [];
let ring = null;
geoPath(projection, {
  moveTo(x, y) { ring = [[x, y]]; rings.push(ring); },
  lineTo(x, y) { ring.push([x, y]); },
  closePath() {},
  arc() {},
}).call(null, land);

const mask = new Uint8Array(W * H);
for (let row = 0; row < H; row++) {
  const y = row + 0.5;
  const xs = [];
  for (const r of rings) {
    for (let i = 0; i < r.length; i++) {
      const [x1, y1] = r[i];
      const [x2, y2] = r[(i + 1) % r.length];
      if ((y1 <= y && y2 > y) || (y2 <= y && y1 > y)) xs.push(x1 + ((y - y1) / (y2 - y1)) * (x2 - x1));
    }
  }
  xs.sort((a, b) => a - b);
  for (let i = 0; i + 1 < xs.length; i += 2) {
    const from = Math.max(0, Math.ceil(xs[i] - 0.5));
    const to = Math.min(W - 1, Math.floor(xs[i + 1] - 0.5));
    for (let c = from; c <= to; c++) mask[row * W + c] ^= 1;
  }
}

// runs alternate water, land, water… across the flattened rows, in base 36
const runs = [];
let cur = 0;
let n = 0;
for (const v of mask) {
  if (v === cur) n++;
  else { runs.push(n); cur = v; n = 1; }
}
runs.push(n);
const land01 = mask.reduce((a, b) => a + b, 0) / mask.length;

const out = `// Generated by scripts/gen-landmask.mjs from Natural Earth 1:50m land (public domain). Don't edit by hand.
// ${W} × ${H} equirectangular cells (row 0 = 90°N, column 0 = 180°W), run-length encoded:
// base-36 run lengths alternating water, land, water… across the rows. ${(land01 * 100).toFixed(1)}% land.

export const LAND_W = ${W};
export const LAND_H = ${H};
export const LAND_RLE = '${runs.map((r) => r.toString(36)).join(',')}';

let cache: Uint8Array | null = null;

/** 1 where there is land, row-major from the north-west corner. */
export function landMask(): Uint8Array {
  if (cache) return cache;
  const mask = new Uint8Array(LAND_W * LAND_H);
  let at = 0;
  let land = 0;
  for (const run of LAND_RLE.split(',')) {
    const n = parseInt(run, 36);
    if (land) mask.fill(1, at, at + n);
    at += n;
    land ^= 1;
  }
  cache = mask;
  return mask;
}

/** Whether a latitude / longitude (degrees) is on land. */
export function isLand(mask: Uint8Array, lat: number, lon: number): boolean {
  const row = Math.min(LAND_H - 1, Math.max(0, Math.floor(((90 - lat) / 180) * LAND_H)));
  const col = ((Math.floor(((lon + 180) / 360) * LAND_W) % LAND_W) + LAND_W) % LAND_W;
  return mask[row * LAND_W + col] === 1;
}
`;
writeFileSync(new URL('../client/src/control/engine/landmask.ts', import.meta.url), out);
console.log(`landmask: ${runs.length} runs, ${(out.length / 1024).toFixed(1)} KB, ${(land01 * 100).toFixed(1)}% land`);
